def build():
    regions = json.loads(REGIONS_PATH.read_text(encoding="utf-8"))
    missing = sorted(set(regions) - set(META))
    extra = sorted(set(META) - set(regions))
    if missing or extra:
        raise SystemExit(f"regions.json과 맞지 않습니다. 빠짐: {missing}, 남음: {extra}")
    out = {}
    for code in regions:
        bortle, elev, *flags = META[code]
        out[code] = {"bortle": bortle, "elev": elev, "water": W in flags, "basin": B in flags}
    return out


def main():
    out = build()
    OUT_PATH.write_text(json.dumps(out, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print(f"{len(out)}개 지역 -> {OUT_PATH}")


if __name__ == "__main__":
    main()
